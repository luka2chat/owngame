/**
 * UI language tables. Game code stores messages as `{ key, params }` and the HUD translates at draw
 * time, so switching language also rewrites banners and kill-feed lines already on screen.
 */
export type Lang = 'zh' | 'en'
export const LANGS: Lang[] = ['zh', 'en']
export const LANG_LABEL: Record<Lang, string> = { zh: '简体中文', en: 'English' }

export type Params = Record<string, string | number | null | undefined>
export type Msg = { key: Key; params?: Params }
type Entry = string | ((p: Params) => string)

const STORE = 'wowfps.lang'

function detect(): Lang {
  const fromUrl = typeof location !== 'undefined' ? new URLSearchParams(location.search).get('lang') : null
  if (fromUrl === 'zh' || fromUrl === 'en') return fromUrl
  try {
    const saved = localStorage.getItem(STORE)
    if (saved === 'zh' || saved === 'en') return saved
  } catch {
    // storage blocked
  }
  const nav = typeof navigator !== 'undefined' ? navigator.language : 'zh'
  return nav.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

let current: Lang = detect()
const listeners = new Set<(lang: Lang) => void>()

export function lang(): Lang {
  return current
}

export function setLang(next: Lang): void {
  if (next === current) return
  current = next
  try {
    localStorage.setItem(STORE, next)
  } catch {
    // storage blocked
  }
  if (typeof document !== 'undefined') document.documentElement.lang = next === 'zh' ? 'zh-CN' : 'en'
  for (const fn of listeners) fn(next)
}

export function onLangChange(fn: (lang: Lang) => void): () => void {
  listeners.add(fn)
  return () => listeners.delete(fn)
}

