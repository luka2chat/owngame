import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const sha=b=>createHash('sha256').update(b).digest('hex');
test('native Vite export retains editable imports and only reviewed assets',async t=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'owngame-vite-export-'));
 t.after(()=>fs.rm(root,{recursive:true,force:true}));
 const put=async(p,s)=>{const f=path.join(root,p);await fs.mkdir(path.dirname(f),{recursive:true});await fs.writeFile(f,s)};
 const spec={fixture:{project:'source',kind:'vite',sourceEntry:'src/main.ts',assetManifest:'public-assets.json',sourceFiles:['public-assets.json','tsconfig.json']}};
 await put('scripts/games/projects.json',JSON.stringify(spec));await put('LICENSE','MIT fixture');
 for(const n of ['build-template.mjs','serve-template.mjs'])await put('scripts/games/'+n,'// fixture');
 await put('source/src/main.ts',"import './style.css';export const ready:boolean=true;");await put('source/src/style.css','body{color:teal}');
 await put('source/src/.DS_Store','private Finder metadata');await put('source/src/.cache/state.json','private cache');
 const html='<html><head></head><body><script type="module" src="./src/main.ts"></script></body></html>';
 await put('source/index.html',html);await put('source/tsconfig.json','{}');
 await put('source/package.json',JSON.stringify({dependencies:{three:'0.186.1','@dimforge/rapier3d-compat':'0.21.0'},devDependencies:{vite:'8.3.1',typescript:'5.9.3'}}));
 const asset=Buffer.from('reviewed');await put('source/public/ok.bin',asset);await put('source/public/private-extra.bin','not reviewed');
 await put('source/public-assets.json',JSON.stringify({files:[{path:'ok.bin',bytes:asset.length,sha256:sha(asset)}]}));
 const body=Buffer.from('<html>frozen</html>');const files=[{bytes:body.length,path:'index.html',sha256:sha(body)}];const version=sha(JSON.stringify(files));
 await put(`library/fixture/${version}/files/index.html`,body);await put(`library/fixture/${version}/delivery.json`,JSON.stringify({entrypoint:'index.html',files}));
 await put('catalog.json',JSON.stringify([{id:'fixture',version,title:'Fixture',description:'Description',instructions:'Play'}]));
 const program='import importlib.util, pathlib, json, sys\ns=importlib.util.spec_from_file_location("exporter",sys.argv[1]);m=importlib.util.module_from_spec(s);s.loader.exec_module(m);r=pathlib.Path(sys.argv[2]);m.ROOT=r;m.export(json.loads((r/"catalog.json").read_text()),r/"out",r/"library")';
 const run=()=>execFileSync('python3',['-c',program,path.resolve('scripts/games/export.py'),root],{encoding:'utf8',stdio:'pipe'});
 run();const out=path.join(root,'out/examples/fixture');
 assert.equal(await fs.readFile(out+'/index.html','utf8'),html);
 assert.equal(await fs.readFile(out+'/public/ok.bin','utf8'),'reviewed');
 await assert.rejects(fs.access(out+'/public/private-extra.bin'));
 await assert.rejects(fs.access(out+'/src/.DS_Store'));await assert.rejects(fs.access(out+'/src/.cache/state.json'));
 const pkg=JSON.parse(await fs.readFile(out+'/package.json'));assert.equal(pkg.dependencies['@dimforge/rapier3d-compat'],'0.21.0');assert.equal(pkg.scripts.typecheck,'tsc --noEmit');
 await put('source/public/ok.bin','changed');assert.throws(run,e=>String(e.stderr).includes('Public asset changed after review'));
});
