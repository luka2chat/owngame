import '../lib/codex-browser-preflight.mjs';
import assert from 'node:assert/strict';
import {mkdtemp,rm,mkdir,writeFile} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {chromium} from 'playwright';
import {createOutlineServer} from '../../apps/outline/server.mjs';
import {newProject,newCard} from '../../apps/outline/model.mjs';

const workspace=await mkdtemp(join(tmpdir(),'outline-gestures-'));
const out=resolve('.local/outline-gestures');await mkdir(out,{recursive:true});
let active,browser;
const results=[];
try{
  active=await createOutlineServer({workspace,port:0});
  const initial=await (await fetch(`${active.url}/api/workspace`)).json();
  const project=newProject('Gesture verification'),card=newCard('note',100,100);
  card.title='Touch this card';card.body='Single-finger drag pans; a tap edits; two fingers zoom.';project.cards.push(card);
  const response=await fetch(`${active.url}/api/workspace`,{method:'PUT',headers:{'Content-Type':'application/json','X-Owngame-Outline':'1'},body:JSON.stringify({revision:initial.revision,workspace:{version:1,activeProjectId:project.id,projects:[...initial.workspace.projects,project]}})});
  assert.equal(response.status,200,await response.text());
  browser=await chromium.launch({headless:true,...(process.env.OWNGAME_CHROME_PATH?{executablePath:process.env.OWNGAME_CHROME_PATH}:{})});
  const desktop=await browser.newPage({viewport:{width:1200,height:900}});
  await desktop.goto(active.url);await desktop.locator('[data-card]').waitFor();
  const read=page=>page.locator('#world').evaluate(el=>{const m=new DOMMatrix(getComputedStyle(el).transform);return{x:m.e,y:m.f,z:m.a};});
  const near=(a,b,epsilon=.1)=>assert.ok(Math.abs(a-b)<epsilon,`${a} != ${b}`);
  const box=await desktop.locator('#viewport').boundingBox(),cx=Math.floor(box.x+box.width*.7)-box.x,cy=Math.floor(box.y+box.height*.7)-box.y;
  await desktop.mouse.move(box.x+cx,box.y+cy);
  const before=await read(desktop);await desktop.mouse.wheel(0,-120);await desktop.waitForFunction(z=>new DOMMatrix(getComputedStyle(document.querySelector('#world')).transform).a!==z,before.z);
  const enlarged=await read(desktop);assert.ok(enlarged.z>before.z);near((cx-before.x)/before.z,(cx-enlarged.x)/enlarged.z);near((cy-before.y)/before.z,(cy-enlarged.y)/enlarged.z);
  await desktop.mouse.wheel(0,120);await desktop.waitForFunction(z=>new DOMMatrix(getComputedStyle(document.querySelector('#world')).transform).a<z,enlarged.z);near((await read(desktop)).z,before.z);
  results.push('Unmodified wheel zooms both directions around the mouse anchor.');
  // Empty top-left remains clear of the centered test card and toolbar.
  await desktop.mouse.move(box.x+15,box.y+15);const prePan=await read(desktop);
  await desktop.mouse.down();await desktop.mouse.move(box.x+75,box.y+55,{steps:5});await desktop.mouse.up();
  const pan=await read(desktop);near(pan.x,prePan.x+60);near(pan.y,prePan.y+40);near(pan.z,prePan.z);
  await desktop.mouse.move(box.x+95,box.y+65);assert.deepEqual(await read(desktop),pan);
  results.push('Held mouse pans; hover after release does not move the canvas.');
  await desktop.close();
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:2});
  await mobile.goto(active.url);await mobile.locator('[data-card]').waitFor();
  const cdp=await mobile.context().newCDPSession(mobile);
  const send=(type,points)=>cdp.send('Input.dispatchTouchEvent',{type,touchPoints:points.map(([id,x,y])=>({id,x,y,radiusX:3,radiusY:3,force:1}))});
  const cardBox=await mobile.locator('[data-card]').boundingBox();const x=cardBox.x+cardBox.width/2,y=cardBox.y+65;
  const start=await read(mobile);
  await send('touchStart',[[1,x,y]]);await send('touchMove',[[1,x+35,y+30]]);await send('touchEnd',[]);
  const single=await read(mobile);near(single.x,start.x+35);near(single.y,start.y+30);near(single.z,start.z);assert.equal(await mobile.locator('#inspector').isVisible(),false);
  results.push('Single-finger drag beginning on card content pans without opening its editor.');
  const pos=()=>mobile.locator('[data-card]').evaluate(el=>({x:el.style.left,y:el.style.top}));const originalCard=await pos();
  const head=await mobile.locator('.card-head').boundingBox();const ax=head.x+35,ay=head.y+head.height/2;
  await send('touchStart',[[1,ax,ay]]);await send('touchMove',[[1,ax+8,ay+5]]);
  const pinchStart=await read(mobile);
  await send('touchStart',[[1,ax+8,ay+5],[2,ax+88,ay+5]]);
  await send('touchMove',[[1,ax-12,ay+15],[2,ax+108,ay+15]]);
  const pinched=await read(mobile);near(pinched.z,Math.min(2,pinchStart.z*1.5));assert.deepEqual(await pos(),originalCard);
  const viewport=await mobile.locator('#viewport').boundingBox();
  near((ax+48-viewport.x-pinchStart.x)/pinchStart.z,(ax+48-viewport.x-pinched.x)/pinched.z);
  near((ay+5-viewport.y-pinchStart.y)/pinchStart.z,(ay+15-viewport.y-pinched.y)/pinched.z);
  await send('touchEnd',[[2,ax+108,ay+15]]);const one=await read(mobile);
  await send('touchMove',[[1,ax+8,ay+25]]);await send('touchEnd',[]);
  const continued=await read(mobile);near(continued.x,one.x+20);near(continued.y,one.y+10);near(continued.z,one.z);
  assert.equal(await mobile.locator('#inspector').isVisible(),false);
  results.push('Pinch anchors at its moving midpoint, rolls back accidental card drag, and continues as one-finger pan without a jump/tap.');
  const vb=await mobile.locator('#viewport').boundingBox();
  await send('touchStart',[[1,vb.x+20,vb.y+30],[2,vb.x+120,vb.y+30]]);const zBeforeCancel=(await read(mobile)).z;
  await send('touchMove',[[1,vb.x+40,vb.y+30],[2,vb.x+100,vb.y+30]]);assert.ok((await read(mobile)).z<zBeforeCancel);
  await send('touchCancel',[]);
  await mobile.locator('#fit').click();
  const tapBox=await mobile.locator('[data-card]').boundingBox();
  await send('touchStart',[[1,tapBox.x+80,tapBox.y+65]]);await send('touchEnd',[]);
  await mobile.locator('#inspector').waitFor({state:'visible'});
  const beforeEditorWheel=await read(mobile);await mobile.locator('#inspector').hover();await mobile.mouse.wheel(0,120);assert.deepEqual(await read(mobile),beforeEditorWheel);
  results.push('Pinch-in and cancellation release gesture state; later card tap edits; editor scrolling does not zoom the canvas.');
  await mobile.screenshot({path:join(out,'mobile.png')});
  await writeFile(join(out,'report.json'),JSON.stringify({status:'passed',scope:'Isolated browser mouse and emulated native multi-touch input; not physical phone acceptance.',checks:results},null,2)+'\n');
  console.log(JSON.stringify({status:'passed',checks:results}));
}finally{
  await browser?.close();if(active)await new Promise(resolve=>active.server.close(resolve));await rm(workspace,{recursive:true,force:true});
}
